-- =====================================================================
--  ESTÚDIO MABE — ERP
--  Estrutura do banco (Supabase / PostgreSQL)
-- =====================================================================
--
--  PARA QUE SERVE
--  O backup .json guarda os DADOS; este arquivo guarda a FORMA onde eles
--  entram. Num desastre total — projeto do Supabase apagado, conta
--  perdida — só o .json não basta: alguém precisa recriar as tabelas
--  antes de poder devolver os registros. É isso que este script faz.
--
--  COMO USAR NUM PROJETO NOVO
--    1. Criar um projeto novo no Supabase.
--    2. Abrir o SQL Editor e rodar este arquivo inteiro.
--    3. Trocar SUPA_URL e SUPA_KEY no index.html pelos do projeto novo
--       (estão juntos, no bloco "SUPABASE" do <script>).
--    4. Antes de abrir o ERP, criar o primeiro acesso: em
--       Authentication > Users, "Add user" com o e-mail e a senha de
--       quem administra (já confirmado: "Auto Confirm User"), e no SQL
--       Editor um cadastro provisório com esse mesmo e-mail:
--         insert into public.usuarios (id, login, nome, role, status)
--         values ('provisorio', 'EMAIL_DE_QUEM_ADMINISTRA',
--                 'Administrador', 'Administrador', 'Ativo');
--    5. Abrir o ERP, entrar com esse e-mail e usar
--       Configurações > Restaurar backup (.json).
--    6. Apagar o cadastro provisório
--         delete from public.usuarios where id = 'provisorio';
--       e conferir em Usuários que só ficaram os cadastros da equipe
--       (excluir o que não for de ninguém da equipe).
--    7. Rodar de novo só o bloco "DEPOIS DO RESTAURO", no fim deste
--       arquivo, para a numeração (ORC, V, OP, OC) seguir do maior
--       número restaurado.
--    8. Criar o bucket `orcamentos-anexos` em Storage, se for usar
--       anexos. O ERP grava ali os anexos e comprovantes e guarda no
--       banco o caminho e o link de cada arquivo (as imagens em si não
--       vêm no .json — ver o LEIA-ME do backup).
--
--  DE ONDE VEIO ESTE ARQUIVO
--  Reconstruído a partir do banco em produção (colunas e tipos lidos
--  pela API REST em 03/10/2026) e das funções `*ParaSupabase` do
--  index.html, que são quem escreve em cada tabela. `madeiras` e
--  `compras` estavam vazias na leitura, então as colunas delas vieram
--  só do código. Revisto em 18/10/2026 contra o index.html: a coluna
--  `num` passou a nascer com sequência própria, os comentários de
--  formato foram completados e o default de `usuarios.role` virou um
--  nível que existe. Revisto em 20/10/2026 (etapa 4 do Financeiro): a
--  coluna `financeiro.comprovantes`, o índice
--  `financeiro_um_por_parcela` e as marcas novas das linhas de
--  pagamento em `vendas.pags`.
--
--  O que a API não revela, e por isso aqui é reconstrução e não cópia:
--  a precisão exata dos números (usei `numeric`, que aceita qualquer
--  valor que o ERP grava), os valores DEFAULT do servidor e os índices
--  além das chaves primárias. O único DEFAULT de que o ERP depende é o
--  da coluna `num` (orcamentos, vendas, producao e compras): o app
--  insere o registro novo sem `num` e lê o número que o banco devolve
--  (insert(...).select()). Por isso `num` aqui é
--  `generated by default as identity` — aceita o número que vem do
--  restauro e gera o próximo sozinho.
--
--  SEGURANÇA
--  As regras de acesso (RLS) e a ligação com o Supabase Auth ficam no
--  `ativar-rls.sql`, nesta mesma pasta, que explica as etapas. Rodar
--  depois deste.
--
--  Rodar duas vezes não quebra nada: tudo é `if not exists`.
-- =====================================================================

