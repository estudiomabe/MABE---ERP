-- Clientes. `doc` guarda CPF ou CNPJ; `id` é o identificador gerado pelo
-- próprio ERP (não é sequencial), por isso text e não uuid.
create table if not exists public.clientes (
  id          text primary key,
  nome        text not null,
  email       text,
  tel         text,
  doc         text,
  cidade      text,
  endereco    text,
  status      text default 'Ativo',
  created_at  timestamptz default now()
);

-- Fornecedores e prestadores de serviço (os dois ficam aqui).
create table if not exists public.fornecedores (
  id          text primary key,
  nome        text not null,
  cnpj        text,
  tel         text,
  email       text,
  cidade      text,
  status      text default 'Ativo',
  created_at  timestamptz default now()
);

-- Portfólio e insumos na mesma tabela, separados por `tipo`
-- ('Portfólio' ou 'Insumo'). `materiais` é a ficha de composição do
-- produto: [{ref, desc, qty, custo}].
create table if not exists public.produtos (
  id          text primary key,
  nome        text not null,
  tipo        text default 'Portfólio',
  cat         text,
  un          text default 'un',
  preco       numeric default 0,
  custo       numeric default 0,
  est         numeric default 0,
  min         numeric default 0,
  materiais   jsonb default '[]'::jsonb,
  created_at  timestamptz default now()
);

-- Estoque de madeira. Medidas em centímetros; o volume em m³ é
-- calculado no ERP, não fica guardado. `custo` é por m³, `min` é o
-- volume mínimo em m³ e `forn` aponta para fornecedores.id.
create table if not exists public.madeiras (
  id          text primary key,
  especie     text not null,
  tipo        text,
  esp         numeric default 0,
  larg        numeric default 0,
  comp        numeric default 0,
  qtd         numeric default 0,
  custo       numeric default 0,
  umidade     numeric default 0,
  min         numeric default 0,
  forn        text,
  created_at  timestamptz default now()
);

-- Máquinas e ferramentas. `ult` é a última manutenção e `intervalo` o
-- número de dias até a próxima.
create table if not exists public.ferramentas (
  id          text primary key,
  nome        text not null,
  tipo        text,
  ult         date,
  intervalo   integer,
  obs         text,
  created_at  timestamptz default now()
);

-- ---------------------------------------------------------------------
--  COMERCIAL
-- ---------------------------------------------------------------------

-- Orçamentos. `itens` é o que vale hoje: cada item carrega a própria
-- ficha de cálculo (materiais, mão de obra, serviços, custos fixos do
-- dia em que foi salvo, impostos, comissão, markup, frete).
-- As colunas `tipo`, `descricao`, `cf`, `mdo`, `materiais`, `imposto`,
-- `markup`, `prod_id`, `qty` e `desc_pct` são de quando um orçamento
-- tinha um item só: o ERP grava vazio ou zero em todas menos
-- `descricao`, que ele não mexe e só lê; ficam para os registros
-- antigos continuarem abrindo.
-- `num` é o número do ORC: o banco gera (o ERP insere sem ele e lê a
-- resposta). Cada item de `itens` leva, entre outros, materiais
-- [{mode, ref, desc, qty, custo}], servicos [{fornId, desc, qtd, valorUn,
-- unidade, valor}], mdo [{tipoId, tipoNome, horas, valorHora}], cf,
-- cfHoras, frete, qty, custo, preco, lucro, descPct (0 sem desconto) e,
-- nos itens montados na ficha, precoCheio, o preço sem desconto (ver a
-- seção 5 do ARQUITETURA.md).
create table if not exists public.orcamentos (
  id          text primary key,
  num         integer generated by default as identity,
  cli_id      text,                      -- aponta para clientes.id
  data        date,
  validade    date,                      -- na prática, a data de entrega combinada
  status      text default 'Rascunho',
  obs         text,
  origem      text,                      -- de onde veio o cliente (Indicação, Instagram...)
  itens       jsonb default '[]'::jsonb,
  anexos      jsonb default '[]'::jsonb,   -- arquivos de referência: { path, nome, url }
  links       jsonb default '[]'::jsonb,   -- links de referencia: { url, nome }
  lixeira     jsonb default '[]'::jsonb,   -- itens excluidos: { item, pos, em, por }
  custo       numeric default 0,
  preco       numeric default 0,
  lucro       numeric default 0,
  op_id       text,
  -- legado (orçamento de item único)
  tipo        text,
  descricao   text,
  cf          jsonb,
  mdo         jsonb,
  materiais   jsonb,
  imposto     numeric default 0,
  markup      numeric default 0,
  prod_id     text,
  qty         numeric,
  desc_pct    numeric default 0,
  created_at  timestamptz default now()
);

-- Pedidos. `pag` guarda o rótulo das formas de pagamento (ex.: "PIX +
-- Cartão de Crédito 3x") e `baixa` diz se o estoque já foi baixado.
-- `num` é o número do V-: o banco gera, como em orcamentos.
-- `pags` é a lista das linhas de pagamento:
--   [{ id, forma, valor, parcelas, data, status, local, comprovantes,
--      sinc, finPendente, semFinanceiro }]
--   `id` é o que o financeiro guarda em pag_id; `forma` é pix, cartao,
--   dinheiro, transferencia ou boleto; `data` é o vencimento; `status` a
--   situação: 'Pendente' (A receber) ou 'Pago' (Já recebido); `local` o
--   local de recebimento;
--   `comprovantes` = [{ path, nome, url }] no Storage (pasta
--   pedidos/<id do pedido>/comprovantes/). É a lista única do pagamento:
--   o lançamento do financeiro ligado à linha (venda_id + pag_id) mostra
--   esta mesma lista, sem cópia.
--   Cada linha é uma conta no financeiro (o cartão, uma por parcela), e
--   três campos opcionais (ausentes quando não se aplicam) guardam a
--   combinação com ele:
--   `sinc` = { valor, data, forma, parcelas, status, taxa, em }: a foto do
--     que o financeiro recebeu da última vez (taxa = % do cartão usada
--     nas parcelas; null quando a linha foi ligada a um lançamento que já
--     existia);
--   `finPendente` = { em, por, origem, decisao? }: a atualização do
--     financeiro desta linha começou e não foi confirmada (origem:
--     'salvar', 'aprovacao', 'assistente' ou 'botao'; decisao: a resposta
--     que o dono deu, 'criar', { ligar: id } , { juntar: id } ou
--     'soMarcarPago'), para a nova tentativa terminar sem perguntar;
--   `semFinanceiro` = { em, por, motivo }: a linha ficou sem lançamento
--     de propósito (motivo: 'excluido', 'movido', 'escolha',
--     'pedidoCancelado' ou 'assistente').
create table if not exists public.vendas (
  id          text primary key,
  num         integer generated by default as identity,
  cli_id      text,                      -- aponta para clientes.id
  data        date,
  itens       jsonb default '[]'::jsonb,   -- [{ prodId, desc, qty, preco }], preco por unidade
  anexos      jsonb default '[]'::jsonb,   -- arquivos de referência: { path, nome, url }
  horas       jsonb default '[]'::jsonb,   -- horas trabalhadas: { data, tipoId, horas, valor, obs }
  pags        jsonb default '[]'::jsonb,   -- linhas de pagamento (ver acima)
  lixeira     jsonb default '[]'::jsonb,   -- itens tirados do pedido: { item, pos, em, por }
  total       numeric default 0,
  pag         text,
  status      text default 'Pendente',
  obs         text,
  origem      text,
  baixa       boolean default false,
  created_at  timestamptz default now()
);

-- ---------------------------------------------------------------------
