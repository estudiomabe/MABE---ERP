  num         integer generated by default as identity,
  titulo      text,
  cli_id      text,                      -- aponta para clientes.id
  orc_id      text,
  prazo       date,
  resp        text,
  prio        text,
  etapa       integer default 0,
  status      text,
  obs         text,
  fim         date,
  created_at  timestamptz default now()
);

create table if not exists public.entregas (
  id          text primary key,
  data        date,
  cli_id      text,                      -- aponta para clientes.id
  op_id       text,
  peca        text,
  endereco    text,
  resp        text,
  status      text,
  obs         text,
  created_at  timestamptz default now()
);

-- ---------------------------------------------------------------------
--  COMPRAS E FINANCEIRO
-- ---------------------------------------------------------------------

-- Ordens de compra. `lancado` marca as que já viraram despesa no
-- financeiro, para não lançar duas vezes. `num` é o número da OC: o
-- banco gera, como em orcamentos.
create table if not exists public.compras (
  id          text primary key,
  num         integer generated by default as identity,
  for_id      text,                      -- aponta para fornecedores.id
  data        date,
  total       numeric default 0,
  status      text,
  obs         text,
  lancado     boolean default false,
  created_at  timestamptz default now()
);

-- Lançamentos financeiros. `tipo` é 'Entrada' ou 'Saída' (com
-- maiúscula e acento, como o ERP grava); `val` é o valor; `status` é
-- 'Pago', 'Pendente' ou 'Cancelado'; `cat` é a coluna Pedido da tela: o
-- rótulo do pedido escolhido ("V-0031 — cliente") ou, nos lançamentos
-- que o ERP cria, um valor genérico ('Pedidos', 'Compras' ou 'Extrato
-- bancário'); a ligação com o pedido fica em `venda_id`. `centro_custo`
-- liga o lançamento a um centro de custo.
--
-- De `origem` para baixo: de onde veio cada lançamento e a que ele está
-- ligado (migracao-financeiro-origem.sql, out/2026). Num banco que já
-- existia antes disso, as colunas entram por aquele arquivo, que também
-- marca a origem dos lançamentos antigos. O index.html confere se elas
-- existem antes de gravar e, sem elas, segue como antes.
--
-- `comprovantes` (migracao-financeiro-comprovantes.sql, out/2026) é a
-- lista própria de quem NÃO é pagamento de pedido (linha do banco sem
-- pedido, despesa à mão, compra, NF): [{ path, nome, url }], arquivos em
-- financeiro/<id>/comprovantes/. O lançamento ligado a uma linha de
-- pagamento mostra a lista da linha (vendas.pags). O lançamento que o
-- pedido cria nasce com id fixo 'p-<pag_id>-<parcela>' (ou
-- 'p-<pag_id>-<parcela>-2', -3… quando o id já foi usado por outro
-- lançamento; repetir a gravação dá "já existe", e não uma conta em
-- dobro).
create table if not exists public.financeiro (
  id            text primary key,
  tipo          text,
  data          date,
  descricao     text,
  cat           text,
  centro_custo  text,
  val           numeric default 0,
  status        text,
  obs           text,
  origem        text,                      -- extrato | pedido | manual | compra | nf
  venda_id      text,                      -- aponta para vendas.id
  pag_id        text,                      -- vendas.pags[i].id (linha de pagamento)
  parcela       integer,                   -- 1..N no cartão; 1 nas outras formas
  parcelas      integer,
  compra_id     text,                      -- aponta para compras.id
  fitid         text,                      -- FITID da transação no extrato OFX
  conta         text not null default '',  -- conta do OFX (BANKID/ACCTID)
  desc_banco    text,                      -- texto original do banco
  lote_ofx      text,                      -- id da importação do extrato
  mesclado_com  text,                      -- lançamento que absorveu este
  mesclagem     jsonb,                     -- o que este recebeu de outro e como era antes
  nao_juntar    jsonb default '[]'::jsonb, -- pares marcados como "não é o mesmo"
  comprovantes  jsonb not null default '[]'::jsonb, -- comprovantes de quem não é pagamento de pedido
  created_at    timestamptz default now()
);

-- ---------------------------------------------------------------------
--  SISTEMA
-- ---------------------------------------------------------------------

-- Usuários do ERP. `login` é o e-mail de acesso. `senha` guarda
-- "sha256$sal$resumo" — não é a senha em si. `role` é o nível de acesso:
-- 'Administrador', 'Financeiro', 'Produção' ou 'Consulta' (os antigos
-- 'Admin', 'Operador' e 'Visualizador' são convertidos ao carregar; o
-- que o ERP não reconhece vira 'Consulta'). `resposta` (da pergunta de
-- segurança) é guardada do mesmo jeito que a senha.
--
-- As colunas `auth_id` e `ultimo` são opcionais: o index.html verifica
-- se existem antes de escrever (`temColuna`). `auth_id` (a conta do
-- Supabase Auth) só é criada ao rodar o `ativar-rls.sql`.
create table if not exists public.usuarios (
  id          text primary key,
  login       text not null,
  senha       text,
  nome        text,
  role        text default 'Consulta',
  status      text default 'Ativo',
  pergunta    text,
  resposta    text,
  created_at  timestamptz default now()
);
-- A coluna `ultimo` (último acesso) é opcional e o ERP funciona sem ela
-- (guarda o último acesso só no aparelho). Ela é texto, no formato que o
-- ERP escreve (data e hora em pt-BR, ex.: "18/10/2026, 14:05:00"), e é
-- criada pela etapa 1 do `ativar-rls.sql`; para criar só ela, basta
-- descomentar:
-- alter table public.usuarios add column if not exists ultimo text;

-- Configurações, no formato campo/valor: cada ajuste do ERP vira uma
-- linha. Os números simples ficam um por linha (aluguel, iptu, agua,
-- energia, contador, outros, hmes, imposto, markup, taxaMaquina,
-- pixAntecipado, taxaParc1 a taxaParc10, saldoInicial). Os valores
-- compostos (custosFixosExtras, mdoTipos, folhaPagamento, empresaInfo,
-- servicos, comissionados, temposProducao, linksProdutos,
-- fretesProdutos, fichasProdutos, saldoBancoOfx) são JSON guardado como
-- texto.
create table if not exists public.config (
  campo       text primary key,
  valor       text,
  updated_at  timestamptz default now()
);

-- Diário de edições. `id` é sequencial do banco (é a única tabela com o
-- id assim; nas outras o id é gerado pelo ERP); `dt` é a data e hora em
-- texto, como o ERP escreve.
create table if not exists public.historico (
  id          bigint generated by default as identity primary key,
  dt          text,
  user_nome   text,
  acao        text,
  modulo      text,
  detalhe     text,
  created_at  timestamptz default now()
);

-- Buscas que o ERP faz com frequência.
create index if not exists idx_orcamentos_num   on public.orcamentos (num desc);
create index if not exists idx_vendas_num       on public.vendas (num desc);
create index if not exists idx_producao_num     on public.producao (num desc);
create index if not exists idx_compras_num      on public.compras (num desc);
create index if not exists idx_financeiro_data  on public.financeiro (data desc);
-- o mesmo FITID não entra duas vezes na mesma conta (índice simples, sem
-- "where": várias linhas sem FITID são permitidas)
create unique index if not exists financeiro_conta_fitid_unico on public.financeiro (conta, fitid);
create index if not exists financeiro_venda_idx on public.financeiro (venda_id);
create index if not exists financeiro_pag_idx   on public.financeiro (pag_id);
-- rede de segurança: uma só conta do pedido ativa por linha de pagamento e
-- parcela (a linha do banco, o cancelado e o mesclado ficam de fora). O
-- ERP já evita a duplicata; com o índice o banco recusa (23505) a que
-- escapar
create unique index if not exists financeiro_um_por_parcela
  on public.financeiro (pag_id, parcela)
  where origem = 'pedido' and pag_id is not null
    and status in ('Pago', 'Pendente') and mesclado_com is null;
create index if not exists idx_historico_id     on public.historico (id desc);
create index if not exists idx_usuarios_login   on public.usuarios (login);

-- =====================================================================
--  Depois de rodar: o banco está vazio e pronto para receber o backup.
--  O número de cada ORC, V, OP e OC novo vem da sequência da coluna
--  `num`, e o restauro (que grava os números antigos) não a faz andar.
--  Por isso, DEPOIS DO RESTAURO, rode de novo o bloco abaixo: ele põe
--  cada sequência logo depois do maior número restaurado. Rodar antes
--  do restauro, ou mais de uma vez, não faz mal.
-- =====================================================================

-- DEPOIS DO RESTAURO
select setval(pg_get_serial_sequence('public.orcamentos', 'num'),
              coalesce((select max(num) from public.orcamentos), 0) + 1, false);
select setval(pg_get_serial_sequence('public.vendas', 'num'),
              coalesce((select max(num) from public.vendas), 0) + 1, false);
select setval(pg_get_serial_sequence('public.producao', 'num'),
              coalesce((select max(num) from public.producao), 0) + 1, false);
select setval(pg_get_serial_sequence('public.compras', 'num'),
              coalesce((select max(num) from public.compras), 0) + 1, false);

-- ---------------------------------------------------------------------
--  Sobre as chaves estrangeiras: as ligações entre tabelas (cli_id,
--  for_id, orc_id, op_id) ficam aqui como comentário, não como
--  constraint. A API REST não mostra quais constraints existem hoje em
--  produção, então preferi não inventá-las: sem elas, um backup antigo
--  entra inteiro mesmo que um cliente tenha sido excluído no meio do
--  caminho — com elas, o restauro falharia. Quem quiser o banco rígido
--  adiciona depois do restauro, com `alter table ... add foreign key`.
-- ---------------------------------------------------------------------
